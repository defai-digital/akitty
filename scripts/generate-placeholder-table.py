#!/usr/bin/env python3
"""Generate Kitty's numeric placeholder alphabet from Unicode 6.0.0 data.

Input: https://www.unicode.org/Public/6.0.0/ucd/UnicodeData.txt
The public graphics protocol fixes this alphabet to combining class 230,
non-decomposing marks, excluding the normalization-sensitive scalars below.
No terminal implementation is used as input. Output is deterministic.
"""
import hashlib
from pathlib import Path
import sys

source = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(source).hexdigest() == '90b45b777346bef027556f9c6cb3ea5d7d745bd60d6762855c08d8a22d34f771', 'Expected Unicode 6.0.0 data'
# The digest is printed for the provenance ledger; protocol facts are validated
# against the fixed alphabet size and endpoints as an additional input check.
excluded = {0x300, 0x301, 0x302, 0x303, 0x304, 0x306, 0x307, 0x308,
            0x309, 0x30a, 0x30b, 0x30c, 0x30f, 0x311, 0x313, 0x314,
            0x342, 0x653, 0x654}
values = []
for line in source.decode().splitlines():
    fields = line.split(';')
    scalar = int(fields[0], 16)
    if fields[2:6] == ['Mn', '230', 'NSM', ''] and scalar not in excluded:
        values.append(scalar)
assert len(values) == 297 and values[0] == 0x305 and values[-1] == 0x1d244
output = '// Generated by scripts/generate-placeholder-table.py from Unicode 6.0.0.\n'
output += '// Protocol data; Unicode license: third_party/unicode/LICENSE.\n'
output += 'pub const DIACRITICS: [u32; 297] = [\n'
for offset in range(0, len(values), 8):
    output += '    ' + ', '.join(f'0x{value:04X}' for value in values[offset:offset + 8]) + ',\n'
output += '];\n'
Path('crates/akitty-core/src/placeholder_table.rs').write_text(output)
print('UnicodeData.txt sha256:', hashlib.sha256(source).hexdigest())
